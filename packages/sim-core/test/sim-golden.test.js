import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fingerprint, runScene } from './golden-lib.js';
import { GOLDEN_SCENES, LEGACY_BUILDING_SCENES, WEDGE_SCENES } from './golden-scenes.js';
import { goldenFor } from './golden-lib.js';

const golden = JSON.parse(readFileSync(new URL('./golden/golden.json', import.meta.url), 'utf8'));
const legacy = JSON.parse(readFileSync(new URL('./golden/golden-phase3.json', import.meta.url), 'utf8'));

const close = (a, b, what) => assert.ok(Math.abs(a - b) <= 1e-6 * Math.max(1, Math.abs(b)) + 1e-9, `${what}: ${a} vs ${b}`);

// Rendered signals must stay identical with no buildings, whatever the reflection order.
for (const order of [undefined, 0, 1, 2]) {
  for (const name of Object.keys(GOLDEN_SCENES)) {
    test(`golden signals: ${name}, reflection_order ${order ?? 'default'}`, () => {
      const { rendered } = runScene(name, order === undefined ? {} : { reflection_order: order });
      rendered.nodes.forEach((n, ni) =>
        n.mics.forEach((m, mi) => {
          const g = golden[name].mics[ni][mi];
          const f = fingerprint(m);
          assert.equal(f.n, g.n);
          for (const k of ['sum', 'sum_sq', 'peak']) close(f[k], g[k], `${name} n${ni} m${mi} ${k}`);
          f.picks.forEach((v, i) => close(v, g.picks[i], `${name} n${ni} m${mi} pick ${i}`));
        })
      );
    });
  }
}

// Bearings against the phase 3 baseline. golden-legacy-analysis.json keeps the pre-change values (windows, SNR and uncertainty changed on purpose).
test('golden bearings (phase 3 baseline)', { skip: process.env.GOLDEN_ANALYSIS === 'off' }, () => {
  for (const name of Object.keys(GOLDEN_SCENES)) {
    const { results } = runScene(name);
    results.forEach((r, si) =>
      r.nodes.forEach((n, ni) => {
        const g = legacy[name].analysis[si].nodes[ni];
        close(n.bearing.azimuth_deg, g.azimuth_deg, `${name} s${si} n${ni} azimuth`);
      })
    );
  }
});

// Analysis values are compared to 1e-8: the GCC-PHAT stage was rewritten for speed after the legacy golden file was made
// (band-limited direct correlation, packed FFTs), which changes the last bits of the bearings (measured worst: 1.3e-10 degrees).
function closeDeep(a, b, what) {
  if (typeof a === 'number' && typeof b === 'number') return assert.ok(Math.abs(a - b) <= 1e-8 * Math.max(1, Math.abs(b)), `${what}: ${a} vs ${b}`);
  if (a && typeof a === 'object') {
    assert.deepEqual(Object.keys(a), Object.keys(b), what);
    for (const k of Object.keys(a)) closeDeep(a[k], b[k], `${what}.${k}`);
    return undefined;
  }
  return assert.equal(a, b, what);
}

// Regression: order 0 and the Maekawa formula (order 1) must stay bit-identical to the code before the wedge model.
// The golden file was generated by that earlier code; do not regenerate it.
const legacyBuildings = JSON.parse(readFileSync(new URL('./golden/golden-legacy-buildings.json', import.meta.url), 'utf8'));
for (const name of Object.keys(LEGACY_BUILDING_SCENES)) {
  test(`legacy golden (bit-identical): ${name}`, () => {
    const now = JSON.parse(JSON.stringify(goldenFor(name, LEGACY_BUILDING_SCENES)));
    assert.deepEqual(now.mics, legacyBuildings[name].mics); // rendered signals: exactly identical
    closeDeep(now.analysis, legacyBuildings[name].analysis, name);
  });
}

// The default model (wedge, order 2) has its own golden set. Regenerate only on purpose (scripts/sim-golden.mjs --set wedge) and say why in NOTES.md.
const wedgeGolden = JSON.parse(readFileSync(new URL('./golden/golden-wedge.json', import.meta.url), 'utf8'));
for (const name of Object.keys(WEDGE_SCENES)) {
  test(`wedge golden: ${name}`, () => {
    const now = JSON.parse(JSON.stringify(goldenFor(name, WEDGE_SCENES)));
    const g = wedgeGolden[name];
    now.mics.forEach((node, ni) =>
      node.forEach((m, mi) => {
        for (const k of ['sum', 'sum_sq', 'peak']) close(m[k], g.mics[ni][mi][k], `${name} n${ni} m${mi} ${k}`);
        m.picks.forEach((v, i) => close(v, g.mics[ni][mi].picks[i], `${name} n${ni} m${mi} pick ${i}`));
      })
    );
    closeDeep(now.analysis, g.analysis, name);
  });
}
