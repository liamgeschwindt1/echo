// Generates docs/diffraction-validation.md: the numbers behind the wedge diffraction model (brief section B7).
// Usage: node scripts/sim-diffraction-validation.mjs [out.md]
import { writeFileSync } from 'node:fs';
import { findPaths } from '../src/geometry.js';
import { diffractionLossDb } from '../src/geometry.js';
import { defaultScenario, newBuilding, newNode, newSource } from '../src/scenario.js';
import { renderScenario } from '../src/render.js';
import { speedOfSound } from '../src/physics.js';
import { DIFFRACTION_REFERENCES, diffractionResponse } from '../src/diffraction.js';
import { C15, PRE_OFFSETS, causalityReport, cornerGeometry, coherentField, db, engineCornerField, exactCornerField, halfPlaneCompare, openSettings } from '../test/wedge-lib.js';
import { referenceRender, diffDb } from '../test/reference-render.js';

const out = process.argv[2] || 'docs/diffraction-validation.md';
const FREQS = [125, 250, 500, 1000, 2000, 4000];
const lines = [];
const w = (s = '') => lines.push(s);
const f1 = (v) => (Number.isFinite(v) ? v.toFixed(2) : String(v));

w('# Wedge diffraction: validation');
w();
w(`Generated by \`node scripts/sim-diffraction-validation.mjs\` (${new Date().toISOString().slice(0, 10)}). Design tool, not validation against measurements: the checks below compare the model with exact or independent numerical solutions of the same idealised problem.`);
w();
w('## Model and references');
w();
w('- Rigid wedge, uniform theory of diffraction (UTD): Kouyoumjian-Pathak coefficient with the Fresnel transition function, spherical incidence, oblique incidence through `sin beta` and `L = s s\' sin^2(beta) / (s + s\')`. A 90 degree building corner is an exterior wedge with `n = 3/2`.');
w('- Why UTD and not BTM in production: it is a closed-form complex frequency response per path, which the frequency-domain renderer, the reach map and the audit can all evaluate cheaply and identically. The Biot-Tolstoy-Medwin (BTM) solution is exact for an infinite rigid wedge and is used here, independently, as the reference.');
w('- Formulas were not taken from memory alone: the coefficient is the four-term cot / F form; the BTM reference is the closed form for an infinite edge. They were cross-checked against each other numerically (the production coefficient and the independent BTM time-domain solution agree to 0.01 dB and 0.3 degrees for half-plane and 90 degree wedge geometries, see `test/sim-wedge.test.js`), and the BTM normalisation was fixed by the exact half-plane shadow-boundary value of one half (-6.02 dB).');
for (const r of DIFFRACTION_REFERENCES) w(`- ${r}`);
w('- Double diffraction (edge to edge): product of the two coefficients with parallel-edge spreading `1/sqrt(s0 s1 s2 (s0+s1+s2))` and the distance parameters `L1 = s0 s1 / (s0 + s1) sin^2 b1`, `L2 = (s0 + s1) s2 / (s0 + s1 + s2) sin^2 b2`. Round the same building the connecting leg runs along a shared face, where each grazing end halves the coefficient (the standard UTD rule for incidence on a face). **This part is an engineering approximation and is not checked against an exact thick-screen solution.** Slope diffraction and vertex (corner point) diffraction are omitted.');
w('- Reflection coefficients inside the wedge coefficient: walls use the simulator wall factor, roofs use 0 (roofs do not reflect in this simulator), so no roof-reflection boundary appears.');
w('- Causality and smooth shadow boundary: see the sections below. Ground effects at edges and facade scattering are not modelled.');
w();

// ---- 2. shadow boundary
w('## 1. Half-plane at the shadow boundary');
w();
w('Exact rigid half-plane (BTM), receiver 0.2 degrees past the shadow boundary (the boundary value is a limit), `rS = rR = 10 m`, source at 15 degrees from the face. Level of the diffracted field alone relative to the free field over the straight distance; at the boundary this is the whole field.');
w();
w('| f (Hz) | exact half-plane (dB) | UTD half-plane (dB) | old Maekawa-type loss (dB) |');
w('|---|---|---|---|');
for (const f of FREQS) {
  const r = halfPlaneCompare({ rS: 10, thS: 15, rR: 10, thR: 195.2, f });
  w(`| ${f} | ${f1(r.exact_db)} | ${f1(r.utd_db)} | ${f1(-diffractionLossDb(0, f, C15))} |`);
}
w();
w('The exact value is -6.02 dB in the high-frequency limit (half the free-field pressure); the old formula gives -4.77 dB at zero path difference. At low frequency the exact level departs from -6 dB because the wavelength is no longer small against the 10 m distances.');
w();
w('### Continuity across the boundary (building corner)');
w();
w('A 1 m arc (`r = 10 m`) across the shadow boundary of a building corner, sampled every 1 cm, full engine (direct, reflection and diffracted paths summed coherently).');
w();
w('| f (Hz) | level at boundary re free field (dB) | largest step between samples (dB) | target |');
w('|---|---|---|---|');
const st = openSettings();
for (const f of FREQS) {
  let prev = null;
  let maxStep = 0;
  let mid = 0;
  const steps = 100;
  const span = (1 / 10) / D2R_(1);
  for (let i = 0; i <= steps; i++) {
    const th = 195 - span / 2 + (i * span) / steps;
    const e = engineCornerField({ rS: 10, thS: 15, rR: 10, thR: th, f, settings: st });
    const l = db(e.field) + 20 * Math.log10(e.straight);
    if (prev !== null) maxStep = Math.max(maxStep, Math.abs(l - prev));
    prev = l;
    if (i === steps / 2) mid = l;
  }
  w(`| ${f} | ${f1(mid)} | ${maxStep.toFixed(3)} | no step > 0.5 dB: ${maxStep <= 0.5 ? 'met' : '**MISSED**'} |`);
}
w();
function D2R_(x) {
  return (x * Math.PI) / 180;
}

// ---- 3. exact comparison
const GEOMS = [
  { rS: 2, rR: 2, alpha: 5 },
  { rS: 10, rR: 10, alpha: 20 },
  { rS: 50, rR: 30, alpha: 10 },
  { rS: 100, rR: 100, alpha: 40 },
  { rS: 5, rR: 40, alpha: 60 },
  { rS: 20, rR: 3, alpha: 30 },
  { rS: 100, rR: 2, alpha: 15 }
];
const THS = 15;
let cells = 0;
let missed = 0;
const worst = { v: 0 };
function table(title, fn) {
  w(title);
  w();
  w(`| rS (m) | rR (m) | shadow angle | ${FREQS.map((f) => `${f} Hz`).join(' | ')} |`);
  w(`|---|---|---|${FREQS.map(() => '---').join('|')}|`);
  for (const g of GEOMS) {
    const row = FREQS.map((f) => {
      const { exact_db, model_db } = fn(g, f);
      if (exact_db < -25) return `n/a (${f1(exact_db)})`;
      const err = model_db - exact_db;
      cells++;
      worst.v = Math.max(worst.v, Math.abs(err));
      const miss = Math.abs(err) > 1.5;
      if (miss) missed++;
      return `${f1(model_db)} vs ${f1(exact_db)} (${err >= 0 ? '+' : ''}${f1(err)})${miss ? ' **MISS**' : ''}`;
    });
    w(`| ${g.rS} | ${g.rR} | ${g.alpha} deg | ${row.join(' | ')} |`);
  }
  w();
}
w('## 2. Comparison with the exact solution');
w();
w('Target (as given in the brief, not loosened): absolute error at most 1.5 dB wherever the exact level is within 25 dB of the free field. Cells further than 25 dB below free field are shown as `n/a` with the exact level. Format: model vs exact (error). Source 15 degrees from the 0-face; the shadow angle is measured from the shadow boundary into the shadow.');
w();
table('### 2a. UTD coefficient against the exact rigid half-plane (diffracted field alone, dB re free field)', (g, f) => {
  const r = halfPlaneCompare({ rS: g.rS, thS: THS, rR: g.rR, thR: THS + 180 + g.alpha, f });
  return { exact_db: r.exact_db, model_db: r.utd_db };
});
const halfCells = { cells, missed, worst: worst.v };
cells = 0;
missed = 0;
worst.v = 0;
table('### 2b. Full engine at a 90 degree building corner against the exact wedge (total field, dB re free field)', (g, f) => {
  const e = engineCornerField({ rS: g.rS, thS: THS, rR: g.rR, thR: THS + 180 + g.alpha, f, settings: st });
  const x = exactCornerField({ rS: g.rS, thS: THS, rR: g.rR, thR: THS + 180 + g.alpha, f });
  const straight = e.straight;
  return { exact_db: db(x) + 20 * Math.log10(straight), model_db: db(e.field) + 20 * Math.log10(straight) };
});
w(`Half-plane table: ${halfCells.cells} cells compared, ${halfCells.missed} outside 1.5 dB, worst ${halfCells.worst.toFixed(2)} dB. Corner table: ${cells} cells compared, ${missed} outside 1.5 dB, worst ${worst.v.toFixed(2)} dB. The corner table includes the far edges of the large test building (extra weak paths) and the wall factor 0.985 in the geometrical-optics terms.`);
w();

// ---- 4. causality
w('## 3. Causality');
w();
{
  const r = causalityReport();
  w('Impulse source (one sample), noise off, node behind a 10 x 10 x 15 m building, direct path blocked (order 2). Both the diffracted response and an ideal delayed impulse (free field, same fractional delay) are band limited at the 48 kHz render rate, so both ring before their arrival; the check is that the diffracted response does not ring more than the ideal impulse.');
  w();
  w(`- Earliest path arrival \`length / c\`: sample ${r.earliest.toFixed(2)}; peak of the rendered response at sample ${r.peak_index}.`);
  w(`- First sample above -20 dB of the peak: ${r.first_above_minus20_db} (arrival minus one sample = ${(Math.floor(r.earliest) - 1)}); first above -40 dB: ${r.first_above_minus40_db}.`);
  w();
  w(`| samples before the peak | ${PRE_OFFSETS.join(' | ')} |`);
  w(`|---|${PRE_OFFSETS.map(() => '---').join('|')}|`);
  w(`| diffracted (dB re peak) | ${r.diffracted.map(f1).join(' | ')} |`);
  w(`| ideal delayed impulse (dB re peak) | ${r.ideal.map(f1).join(' | ')} |`);
  w();
  w(`Requirement: the diffracted contribution does not arrive before \`length / c\` minus one sample. Measured: ${r.first_above_minus20_db >= Math.floor(r.earliest) - 1 ? 'met at the -20 dB level' : '**MISSED at the -20 dB level**'}; below -20 dB the pre-arrival level is band-limiting ringing of the sampled onset (the wedge impulse response has a 1/sqrt(t) onset), compared in the table with the ideal impulse above. The coefficient is evaluated down to 1 Hz: clamping it at 10 Hz was measured to add a -47 dB pre-arrival plateau, so the grid starts at 1 Hz.`);
  w();
}

// ---- 5. frequency behaviour
w('## 4. Frequency behaviour');
w();
{
  const g = cornerGeometry();
  const src = g.pos(10, 15);
  const mic = g.pos(10, 195 + 20);
  const { paths } = findPaths(src, mic, { settings: st, buildings: g.buildings, c: C15 });
  const p = paths.find((q) => q.diffraction?.chain === 'E');
  const lvl = (f) => {
    const [re, im] = diffractionResponse(p.diffraction, f, C15);
    return -20 * Math.log10(Math.hypot(re, im) * p.diffraction.spread * p.length);
  };
  w('Diffraction loss of the single-edge path (corner, receiver 20 degrees into the shadow, `r = 10 m`), relative to a free-field wave over the unfolded length.');
  w();
  w(`| ${FREQS.map((f) => `${f} Hz`).join(' | ')} |`);
  w(`|${FREQS.map(() => '---').join('|')}|`);
  w(`| ${FREQS.map((f) => `${f1(lvl(f))} dB`).join(' | ')} |`);
  w();
  w(`Loss at 250 Hz (${f1(lvl(250))} dB) is smaller than at 4 kHz (${f1(lvl(4000))} dB): ${lvl(250) < lvl(4000) ? 'met' : '**MISSED**'}.`);
  w();
}

// ---- 6. roof edge
w('## 5. Roof edge and edges round the ends');
w();
{
  const s = openSettings({ diffraction_order: 2 });
  const b = [newBuilding('b1', 50, 0, 10, 10, 15)];
  const { paths } = findPaths([0, 0, 1.5], [100, 0, 5], { settings: s, buildings: b, c: C15 });
  w('Node at 100 m, 5 m high, source at 1.5 m, 10 x 10 x 15 m building between them (direct path blocked). Paths found:');
  w();
  w('| type | edges | length (m) | delay (ms) | length / c (ms) |');
  w('|---|---|---|---|---|');
  for (const p of paths) w(`| ${p.type} | ${p.surfaces.join(' + ')} | ${p.length.toFixed(3)} | ${(p.delay_s * 1000).toFixed(3)} | ${((p.length / C15) * 1000).toFixed(3)} |`);
  w();
}

// ---- 7. order 2 canyon
w('## 6. Order 2 in a two-building canyon');
w();
{
  const b = [newBuilding('b1', 40, 8, 14, 6, 12), newBuilding('b2', 40, -8, 14, 6, 12)];
  w('Source (0, 0, 1.5), receiver (90, 0, 3), two 14 x 6 x 12 m buildings either side of the line (clear direct path), ground reflectivity 0.8, reflection order 1.');
  w();
  w('| prune dB | paths kept | E | S+E | E+S | E+E | pruned | path_cap | blocked | off_face |');
  w('|---|---|---|---|---|---|---|---|---|---|');
  for (const prune of [200, 60, 50, 40]) {
    const s = openSettings({ ground_reflectivity: 0.8, diffraction_order: 2, path_prune_db: prune });
    const { paths, dropped } = findPaths([0, 0, 1.5], [90, 0, 3], { settings: s, buildings: b, c: C15 });
    const count = (chain) => paths.filter((p) => p.diffraction?.chain === chain).length;
    const reasons = {};
    for (const d of dropped) reasons[d.reason] = (reasons[d.reason] || 0) + (d.count || 1);
    w(`| ${prune} | ${paths.length} | ${count('E')} | ${count('SE')} | ${count('ES')} | ${count('EE')} | ${reasons.pruned || 0} | ${reasons.path_cap || 0} | ${reasons.blocked || 0} | ${reasons.off_face || 0} |`);
  }
  w();
}

// ---- 8. reference renderer
w('## 7. Reference renderer agreement (production vs independent time-domain render)');
w();
{
  w('| scene | difference (dB re signal rms) |');
  w('|---|---|');
  const scenes = [
    ['blocked direct, order 2, two buildings', [newBuilding('b1', 50, 0, 10, 10, 15), newBuilding('b2', 50, 30, 40, 4, 15)], [100, 0, 5]],
    ['lit receiver near a shadow boundary', [newBuilding('b1', 50, 12, 10, 10, 15)], [100, 0, 5]],
    ['two-building canyon, reflection + diffraction', [newBuilding('b1', 40, 8, 14, 6, 12), newBuilding('b2', 40, -8, 14, 6, 12)], [90, 0, 3]]
  ];
  for (const [name, buildings, nodePos] of scenes) {
    const s = defaultScenario();
    Object.assign(s.settings, { ground_reflectivity: 0.8, reflection_order: 1, diffraction_order: 2, diffraction_model: 'wedge' });
    s.buildings = buildings;
    s.nodes = [{ ...newNode('n1', nodePos[0], nodePos[1]), position: nodePos, mic_spacing_m: 0.05 }];
    s.sources = [{ ...newSource('s1', 'b', 0, 0, 100), keyframes: [{ t: 0, position: [0, 0, 1.5] }], start_s: 0.05 }];
    const clip = new Float32Array(1200).map((_, i) => Math.sin(i * 0.37) * Math.sin(i * 0.011) + Math.sin(i * 1.3) * 0.5);
    const clips = new Map([['b', clip]]);
    const prod = renderScenario(s, clips, { lengthS: 0.9 });
    const ref = referenceRender(s, clips, 0.9);
    let worstD = -Infinity;
    for (let mi = 0; mi < 4; mi++) worstD = Math.max(worstD, diffDb(ref.nodes[0].mics[mi], prod.nodes[0].mics[mi]));
    w(`| ${name} | ${f1(worstD)} |`);
  }
  w();
  w('Target: below -60 dB. The reference evaluates each diffraction coefficient directly on a dense linear grid (no log grid, no interpolation) and builds a time-domain impulse response by inverse FFT.');
  w();
}

w('## 8. Not done / limits');
w();
w('- Optional wave-solver check (`scripts/sim-wavesolver-check.mjs`) was not implemented.');
w('- Double diffraction (including the grazing connecting leg along a face) is not validated against an exact solution.');
w('- A single wedge cannot connect a source and receiver on opposite sides of a building, so at `diffraction_order: 1` such a receiver gets no diffracted path; order 2 is needed for over-the-roof and round-the-ends paths.');
w('- Ground effects at edges, facade scattering, slope diffraction and vertex diffraction are not modelled.');
w();

writeFileSync(new URL(`../${out}`, import.meta.url), lines.join('\n'));
console.log(`wrote ${out}`);
