// Paths pruned per scene at path_prune_db 40, 50 and 60 (and with pruning effectively off), and the effect on the bearing error.
// Bearing error is computed on scenes 2 only (scene 3 takes minutes per render); counts are reported for all three scenes.
import { writeFileSync } from 'node:fs';
import { PROFILE_SCENES } from '../test/profile-scenes.js';
import { computePathTable } from '../src/sim/core/geometry.js';
import { micPositions } from '../src/sim/core/mics.js';
import { speedOfSound } from '../src/sim/core/physics.js';
import { renderScenario } from '../src/sim/core/render.js';
import { analyseScenario } from '../src/sim/core/analyse.js';

const out = process.argv[2] || 'docs/prune-report.md';
const LEVELS = [200, 60, 50, 40];
const lines = ['# Path pruning report', '', 'Generated by `node scripts/sim-prune-report.mjs`. Wedge model, diffraction order 2. 200 dB means no pruning. Counts are over every source, node and microphone.', '', '| scene | prune dB | paths kept | pruned | path_cap | blocked (incl. not visible) | off_face |', '|---|---|---|---|---|---|---|'];
for (const name of Object.keys(PROFILE_SCENES)) {
  for (const db of LEVELS) {
    const { scenario } = PROFILE_SCENES[name]({ path_prune_db: db });
    const table = computePathTable(scenario, (node) => micPositions(node), speedOfSound(scenario.settings.temperature_c));
    const tally = { kept: 0, pruned: 0, path_cap: 0, blocked: 0, off_face: 0 };
    for (const node of table) {
      for (const mic of node.perMic) {
        for (const r of mic) {
          tally.kept += r.paths.length;
          for (const d of r.dropped) tally[d.reason] = (tally[d.reason] || 0) + (d.count || 1);
        }
      }
    }
    lines.push(`| ${name} | ${db} | ${tally.kept} | ${tally.pruned} | ${tally.path_cap} | ${tally.blocked} | ${tally.off_face} |`);
    console.log(lines.at(-1));
  }
}

lines.push('', '## Effect on the bearing error (scene 2, mean over nodes, degrees from the true direction)', '', '| prune dB | n1 | n2 |', '|---|---|---|');
const unit = (az, el) => {
  const r = (d) => (d * Math.PI) / 180;
  return [Math.cos(r(el)) * Math.cos(r(az)), Math.cos(r(el)) * Math.sin(r(az)), Math.sin(r(el))];
};
for (const db of LEVELS) {
  const { scenario, clips, lengthS } = PROFILE_SCENES.scene2_three_buildings({ path_prune_db: db });
  const clipMap = new Map(Object.entries(clips));
  const durations = new Map(Object.entries(clips).map(([k, v]) => [k, v.length / 48000]));
  const results = analyseScenario(scenario, renderScenario(scenario, clipMap, { lengthS }), durations);
  const errs = results[0].nodes.map((n) => {
    if (!n.bearing) return 'no bearing';
    const t = unit(n.true_azimuth_deg, n.true_elevation_deg);
    const d = n.bearing.direction;
    return (Math.acos(Math.max(-1, Math.min(1, d[0] * t[0] + d[1] * t[1] + d[2] * t[2]))) * 180 / Math.PI).toFixed(3);
  });
  lines.push(`| ${db} | ${errs.join(' | ')} |`);
  console.log(lines.at(-1));
}
lines.push('');
writeFileSync(new URL(`../${out}`, import.meta.url), lines.join('\n'));
console.log(`wrote ${out}`);
