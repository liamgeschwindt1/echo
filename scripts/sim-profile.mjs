// Stage timing of Create on three scenes. Usage: node scripts/sim-profile.mjs <out.md> [--legacy] [--title "text"]
//   --legacy   diffraction_order 0 and model maekawa on every scene (the old default), for docs/profile-before.md
// Scene 3 uses diffraction_order 0 in the "before" table, as specified; otherwise every scene runs at the default settings.
import { writeFileSync } from 'node:fs';
import { PROFILE_SCENES } from '../test/profile-scenes.js';
import { renderScenario } from '../src/sim/core/render.js';
import { analyseScenario } from '../src/sim/core/analyse.js';
import { newProfile } from '../src/sim/core/profile.js';
import { computeReachField, noiseBandPowerPa2, sourceBandLevels } from '../src/sim/core/reach.js';
import { speedOfSound } from '../src/sim/core/physics.js';

const args = process.argv.slice(2);
const out = args.find((a) => !a.startsWith('--')) || 'docs/profile.md';
const legacy = args.includes('--legacy');
const overrides = legacy ? { diffraction_order: 0, diffraction_model: 'maekawa' } : {};

const fmt = (ms) => (ms >= 1000 ? `${(ms / 1000).toFixed(2)} s` : `${ms.toFixed(0)} ms`);
const rows = [];
const notes = [];
for (const [name, build] of Object.entries(PROFILE_SCENES)) {
  const { scenario, clips, lengthS } = build(overrides);
  const clipMap = new Map(Object.entries(clips));
  const profile = newProfile();
  const t0 = performance.now();
  const rendered = renderScenario(scenario, clipMap, { lengthS, profile });
  const renderMs = performance.now() - t0;
  const durations = new Map(Object.entries(clips).map(([k, v]) => [k, v.length / 48000]));
  const t1 = performance.now();
  const results = analyseScenario(scenario, rendered, durations, { progressive: true, profile });
  const analyseMs = performance.now() - t1;
  const s = scenario.settings;
  const n = 2 ** Math.ceil(Math.log2(rendered.length));
  const pathCounts = rendered.paths.flatMap((node) => node.perMic.flatMap((mic) => mic.map((r) => r.paths.length)));
  const dropped = {};
  for (const node of rendered.paths) for (const mic of node.perMic) for (const r of mic) for (const d of r.dropped) dropped[d.reason] = (dropped[d.reason] || 0) + (d.count || 1);
  // Reach map for one source, 4 m cells over the scene.
  const src = scenario.sources[0];
  const samples = clipMap.get(src.clip);
  const bandPa2 = sourceBandLevels(samples, 48000, src.level_1m_db, s.localisation_band_hz);
  const grid = { kind: 'plan', x0: -40, y0: -40, cell: 4, nx: 50, ny: 38, z: s.slice_height_m };
  const t2 = performance.now();
  computeReachField({ sources: [{ position: src.keyframes[0].position, bandPa2 }], settings: s, buildings: scenario.buildings, grid, noisePa2: noiseBandPowerPa2(s) });
  const reachMs = performance.now() - t2;
  const ms = profile.ms;
  rows.push({
    name,
    order: s.diffraction_order,
    model: s.diffraction_model ?? 'maekawa (legacy)',
    prepare: (ms.clip_spectra || 0) + (ms.path_table || 0),
    clip_spectra: ms.clip_spectra || 0,
    path_table: ms.path_table || 0,
    mic_render: ms.mic_render || 0,
    noise: ms.noise || 0,
    activity: ms.activity || 0,
    localise_final: ms.localise_final || 0,
    localise_progressive: ms.localise_progressive || 0,
    path_report: ms.path_report || 0,
    analysis: analyseMs - (ms.backtrace || 0) - (ms.localise_final || 0) - (ms.localise_progressive || 0) - (ms.path_report || 0),
    backtrace: ms.backtrace || 0,
    total: renderMs + analyseMs,
    reach: reachMs,
    n,
    bins: n / 2 + 1,
    paths_min: Math.min(...pathCounts),
    paths_max: Math.max(...pathCounts),
    paths_mean: pathCounts.reduce((a, b) => a + b, 0) / pathCounts.length,
    dropped
  });
  notes.push(`${name}: ${scenario.nodes.length} nodes, ${scenario.sources.length} sources, ${scenario.buildings.length} buildings, ${lengthS} s render`);
  console.log(name, fmt(renderMs + analyseMs));
  void results;
}
const head = ['Stage', ...rows.map((r) => r.name)];
const line = (label, f) => `| ${label} | ${rows.map(f).join(' | ')} |`;
const md = [
  `# ${args.find((a) => a.startsWith('--title='))?.slice(8) || (legacy ? 'Profile before (legacy diffraction, order 0)' : 'Profile')}`,
  '',
  `Generated by \`node scripts/sim-profile.mjs ${out}${legacy ? ' --legacy' : ''}\` on node ${process.version}, ${new Date().toISOString().slice(0, 10)}. Single run, wall clock, one thread; expect run-to-run noise of a few percent.`,
  '',
  ...notes.map((n) => `- ${n}`),
  '',
  `| ${head.join(' | ')} |`,
  `|${head.map(() => '---').join('|')}|`,
  line('diffraction order / model', (r) => `${r.order} / ${r.model}`),
  line('prepareRender: clip spectra', (r) => fmt(r.clip_spectra)),
  line('prepareRender: path table', (r) => fmt(r.path_table)),
  line('per-microphone render (all mics, paths x bins + irfft)', (r) => fmt(r.mic_render)),
  line('noise generation', (r) => fmt(r.noise)),
  line('activity (decimated, per node)', (r) => fmt(r.activity)),
  line('analysis: bearing, full window (GCC-PHAT, 6 pairs)', (r) => fmt(r.localise_final)),
  line('analysis: progressive bearings (growing windows, UI wedges)', (r) => fmt(r.localise_progressive)),
  line('analysis: path report', (r) => fmt(r.path_report)),
  line('analysis: windows, uncertainty, SNR, fix (rest)', (r) => fmt(r.analysis)),
  line('back-trace', (r) => fmt(r.backtrace)),
  line('**Create total**', (r) => `**${fmt(r.total)}**`),
  line('reach map, one source (4 m cells, 50 x 38)', (r) => fmt(r.reach)),
  line('FFT size', (r) => String(r.n)),
  line('bins per microphone', (r) => String(r.bins)),
  line('paths per source and mic (min / mean / max)', (r) => `${r.paths_min} / ${r.paths_mean.toFixed(1)} / ${r.paths_max}`),
  line('dropped candidates by reason', (r) => Object.entries(r.dropped).map(([k, v]) => `${k} ${v}`).join(', ') || 'none'),
  ''
].join('\n');
writeFileSync(new URL(`../${out}`, import.meta.url), md);
console.log(`wrote ${out}`);
